#!/usr/bin/env python3
"""
AuraUI CLI - Build, Bundle, and Scaffold Modern C++ Desktop Apps with HTML/CSS UI
"""

import os
import sys
import shutil
import subprocess
import argparse
import json
from pathlib import Path

FRAMEWORK_ROOT = Path(__file__).resolve().parent.parent

def generate_vfs_header(directory: Path, output_header: Path):
    """Embeds an entire directory of HTML, CSS, JS into a C++ Virtual File System header"""
    files = []
    for root, _, filenames in os.walk(directory):
        for filename in filenames:
            filepath = Path(root) / filename
            relative_path = filepath.relative_to(directory).as_posix()
            if not relative_path.startswith('/'):
                relative_path = '/' + relative_path
            files.append((relative_path, filepath))

    with open(output_header, 'w', encoding='utf-8') as header:
        header.write('// Auto-generated by AuraUI Asset Bundler\n')
        header.write('#ifndef AURAUI_VFS_H\n')
        header.write('#define AURAUI_VFS_H\n\n')
        header.write('#include "webui.h"\n')
        header.write('#include <cstring>\n')
        header.write('#include <cstdio>\n\n')

        header.write('typedef struct {\n')
        header.write('    const char *path;\n')
        header.write('    const unsigned char *data;\n')
        header.write('    int length;\n')
        header.write('} AuraVirtualFile;\n\n')

        for i, (relative_path, filepath) in enumerate(files):
            with open(filepath, 'rb') as f:
                data = f.read()
                header.write(f'static const unsigned char FILE_{i}[] = {{')
                header.write(','.join(f'0x{byte:02x}' for byte in data))
                header.write('};\n\n')

        header.write('static const AuraVirtualFile aura_virtual_files[] = {\n')
        for i, (relative_path, filepath) in enumerate(files):
            with open(filepath, 'rb') as f:
                data = f.read()
                header.write('    {\n')
                header.write(f'        "{relative_path}",\n')
                header.write(f'        FILE_{i},\n')
                header.write(f'        {len(data)}\n')
                header.write('    },\n')
        if not files:
            header.write('    {nullptr, nullptr, 0}\n')
        header.write('};\n\n')

        header.write('static const int aura_virtual_files_count = sizeof(aura_virtual_files) / sizeof(aura_virtual_files[0]);\n\n')

        header.write('inline const void* aura_vfs_handler(const char* path, int* length) {\n')
        header.write('    for (int i = 0; i < aura_virtual_files_count; ++i) {\n')
        header.write('        if (aura_virtual_files[i].path != nullptr) {\n')
        header.write('            if (strcmp(aura_virtual_files[i].path, path) == 0) {\n')
        header.write('                const char* content_type = webui_get_mime_type(path);\n')
        header.write('                const char* header_tmpl = "HTTP/1.1 200 OK\\r\\n"\n')
        header.write('                                          "Content-Type: %s\\r\\n"\n')
        header.write('                                          "Content-Length: %d\\r\\n"\n')
        header.write('                                          "Cache-Control: no-cache\\r\\n\\r\\n";\n')
        header.write('                int file_len = aura_virtual_files[i].length;\n')
        header.write('                int h_len = snprintf(nullptr, 0, header_tmpl, content_type, file_len);\n')
        header.write('                *length = h_len + file_len;\n')
        header.write('                unsigned char* resp = (unsigned char*)webui_malloc(*length);\n')
        header.write('                snprintf((char*)resp, h_len + 1, header_tmpl, content_type, file_len);\n')
        header.write('                memcpy(resp + h_len, aura_virtual_files[i].data, file_len);\n')
        header.write('                return resp;\n')
        header.write('            }\n')
        header.write('        }\n')
        header.write('    }\n')
        header.write('    return nullptr;\n')
        header.write('}\n\n')
        header.write('#endif // AURAUI_VFS_H\n')

    print(f"[AuraUI] Bundled {len(files)} UI assets into {output_header.name}")


def cmd_new(args):
    """Scaffold a new AuraUI project"""
    project_name = args.name
    dest = Path.cwd() / project_name
    if dest.exists():
        print(f"[Error] Directory '{project_name}' already exists.")
        sys.exit(1)

    template_dir = FRAMEWORK_ROOT.parent / "templates" / "default"
    dest.mkdir(parents=True)
    (dest / "src").mkdir()
    (dest / "ui").mkdir()

    # Copy template files
    for item in (template_dir / "src").glob("*"):
        shutil.copy(item, dest / "src")

    for item in (template_dir / "ui").glob("*"):
        shutil.copy(item, dest / "ui")

    # Copy framework bridge files into ui folder
    shutil.copy(FRAMEWORK_ROOT / "cli" / "aura.js", dest / "ui" / "aura.js")
    shutil.copy(FRAMEWORK_ROOT / "cli" / "aura.css", dest / "ui" / "aura.css")

    # Write project configuration
    config = {
        "name": project_name,
        "title": project_name.replace("-", " ").title(),
        "width": 1050,
        "height": 720,
        "framework_path": str(FRAMEWORK_ROOT)
    }
    with open(dest / "auraui.json", "w") as f:
        json.dump(config, f, indent=2)

    print(f"\n[AuraUI] Successfully created AuraUI project '{project_name}'!")
    print(f"   cd {project_name}")
    print("   auraui dev    # Run in live development mode")
    print("   auraui build  # Compile standalone optimized .exe\n")


def cmd_bundle(args):
    """Bundle the UI assets into C++ header"""
    ui_dir = Path(args.ui_dir or "ui")
    out_file = Path(args.output or "src/vfs.h")
    out_file.parent.mkdir(parents=True, exist_ok=True)
    generate_vfs_header(ui_dir, out_file)


def find_vcvarsall():
    """Detect MSVC vcvarsall.bat"""
    vswhere = Path(r"C:\Program Files (x86)\Microsoft Visual Studio\Installer\vswhere.exe")
    if vswhere.exists():
        cmd = f'"{vswhere}" -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath'
        res = subprocess.run(cmd, capture_output=True, text=True, shell=True)
        if res.returncode == 0 and res.stdout.strip():
            vs_path = Path(res.stdout.strip())
            vcvars = vs_path / "VC" / "Auxiliary" / "Build" / "vcvarsall.bat"
            if vcvars.exists():
                return vcvars
    return None


def cmd_build(args):
    """Compile project into standalone .exe with embedded UI"""
    cwd = Path.cwd()
    src_dir = cwd / "src"
    ui_dir = cwd / "ui"
    dist_dir = cwd / "dist"
    dist_dir.mkdir(parents=True, exist_ok=True)

    # 1. Ensure bridge assets exist in ui folder without overwriting user customizations
    if not (ui_dir / "aura.js").exists():
        shutil.copy(FRAMEWORK_ROOT / "cli" / "aura.js", ui_dir / "aura.js")
    if not (ui_dir / "aura.css").exists():
        shutil.copy(FRAMEWORK_ROOT / "cli" / "aura.css", ui_dir / "aura.css")

    # 2. Bundle UI to vfs.h
    print("\n[AuraUI] [1/2] Bundling HTML/CSS/JS assets into C++ binary...")
    vfs_header = src_dir / "vfs.h"
    generate_vfs_header(ui_dir, vfs_header)

    # 3. Compile with MSVC
    print("[AuraUI] [2/2] Compiling standalone executable with MSVC...")
    vcvars = find_vcvarsall()
    if not vcvars:
        print("[Error] Visual Studio C++ Build Tools (MSVC) not found.")
        sys.exit(1)

    app_name = cwd.name
    out_exe = dist_dir / f"{app_name}.exe"

    includes = [
        f'/I"{FRAMEWORK_ROOT / "include"}"',
        f'/I"{FRAMEWORK_ROOT / "include" / "nlohmann"}"',
        f'/I"{src_dir}"'
    ]
    lib_path = FRAMEWORK_ROOT / "lib" / "webui-2-static.lib"

    cpp_sources = list(src_dir.glob("*.cpp"))
    cpp_files_arg = " ".join(f'"{f}"' for f in cpp_sources) if cpp_sources else f'"{src_dir / "main.cpp"}"'

    # MSVC compile command
    compile_cmd = (
        f'call "{vcvars}" x64 && '
        f'cl.exe /nologo /std:c++20 /O2 /MD /EHsc '
        f'{" ".join(includes)} '
        f'{cpp_files_arg} '
        f'"{lib_path}" '
        f'user32.lib advapi32.lib shell32.lib ole32.lib comdlg32.lib '
        f'/Fe:"{out_exe}" '
        f'/link /SUBSYSTEM:WINDOWS /ENTRY:mainCRTStartup'
    )

    result = subprocess.run(compile_cmd, shell=True, capture_output=True, text=True)
    if result.returncode != 0:
        print("[Error] Compilation failed:")
        print(result.stdout)
        print(result.stderr)
        sys.exit(1)

    # Clean intermediate files
    for obj in cwd.glob("*.obj"):
        try: os.remove(obj)
        except: pass

    size_kb = out_exe.stat().st_size / 1024.0
    print(f"\n[AuraUI] Build Succeeded!")
    print(f"   Binary: {out_exe}")
    print(f"   Size:   {size_kb:.1f} KB (Completely standalone single executable!)\n")


def cmd_dev(args):
    """Run in development mode (using local HTML/CSS files)"""
    cwd = Path.cwd()
    src_dir = cwd / "src"
    ui_dir = cwd / "ui"
    build_dir = cwd / "build_dev"
    build_dir.mkdir(parents=True, exist_ok=True)

    # Ensure bridge assets exist without overwriting user edits
    if not (ui_dir / "aura.js").exists():
        shutil.copy(FRAMEWORK_ROOT / "cli" / "aura.js", ui_dir / "aura.js")
    if not (ui_dir / "aura.css").exists():
        shutil.copy(FRAMEWORK_ROOT / "cli" / "aura.css", ui_dir / "aura.css")

    # Clean any stale vfs.h in dev mode so C++ loads live files from disk
    vfs_header = src_dir / "vfs.h"
    if vfs_header.exists():
        try: os.remove(vfs_header)
        except: pass

    print("[AuraUI] Starting development build...")
    vcvars = find_vcvarsall()
    if not vcvars:
        print("[Error] Visual Studio C++ Build Tools (MSVC) not found.")
        sys.exit(1)

    out_exe = build_dir / "app_dev.exe"
    includes = [
        f'/I"{FRAMEWORK_ROOT / "include"}"',
        f'/I"{FRAMEWORK_ROOT / "include" / "nlohmann"}"',
        f'/I"{src_dir}"'
    ]
    lib_path = FRAMEWORK_ROOT / "lib" / "webui-2-static.lib"

    cpp_sources = list(src_dir.glob("*.cpp"))
    cpp_files_arg = " ".join(f'"{f}"' for f in cpp_sources) if cpp_sources else f'"{src_dir / "main.cpp"}"'

    compile_cmd = (
        f'call "{vcvars}" x64 && '
        f'cl.exe /nologo /std:c++20 /MD /EHsc /DAURA_DEV_MODE '
        f'{" ".join(includes)} '
        f'{cpp_files_arg} '
        f'"{lib_path}" '
        f'user32.lib advapi32.lib shell32.lib ole32.lib comdlg32.lib '
        f'/Fe:"{out_exe}"'
    )

    result = subprocess.run(compile_cmd, shell=True, capture_output=True, text=True)
    if result.returncode != 0:
        print("[Error] Compilation failed:")
        print(result.stdout)
        print(result.stderr)
        sys.exit(1)

    print(f"[AuraUI] Launching {out_exe.name}...")
    subprocess.run(f'"{out_exe}"', shell=True)


def main():
    parser = argparse.ArgumentParser(description="AuraUI CLI - Modern C++ Desktop Apps with HTML/CSS")
    subparsers = parser.add_subparsers(dest="command")

    # new / init
    p_new = subparsers.add_parser("new", help="Create a new AuraUI project")
    p_new.add_argument("name", help="Project name")

    p_init = subparsers.add_parser("init", help="Create a new AuraUI project")
    p_init.add_argument("name", help="Project name")

    # bundle
    p_bundle = subparsers.add_parser("bundle", help="Bundle UI assets into C++ header")
    p_bundle.add_argument("--ui-dir", default="ui", help="Path to UI assets folder")
    p_bundle.add_argument("--output", default="src/vfs.h", help="Output header path")

    # dev
    subparsers.add_parser("dev", help="Run in dev mode")

    # build
    subparsers.add_parser("build", help="Build standalone release .exe")

    args = parser.parse_args()
    if args.command in ("new", "init"):
        cmd_new(args)
    elif args.command == "bundle":
        cmd_bundle(args)
    elif args.command == "dev":
        cmd_dev(args)
    elif args.command == "build":
        cmd_build(args)
    else:
        parser.print_help()

if __name__ == "__main__":
    main()
